// Build-only: turn the verified Vite output into immutable native resources.
import { createHash } from 'node:crypto'
import { lstat, mkdir, readFile, readdir, rename, writeFile } from 'node:fs/promises'
import { dirname, join, resolve } from 'node:path'
import { gzipSync } from 'node:zlib'
import { parseArgs } from 'node:util'

const { values } = parseArgs({ options: { dist: { type: 'string' }, output: { type: 'string' } } })
if (!values.dist || !values.output) throw new Error('--dist and --output are required')
const root = resolve(values.dist)
const files = []
async function visit(directory, prefix = '') {
  for (const name of (await readdir(directory)).sort()) {
    if (!/^[a-zA-Z0-9_.-]+$/.test(name)) throw new Error(`Invalid asset name: ${name}`)
    const path = join(directory, name), info = await lstat(path), relative = prefix + name
    if (info.isSymbolicLink()) throw new Error('Symlinks are not production assets')
    if (info.isDirectory() && relative === 'assets') await visit(path, relative + '/')
    else if (info.isFile() && (relative === 'index.html' || /^assets\/[a-zA-Z0-9_.-]+-[a-zA-Z0-9_-]{8,}\.(js|css|svg|png|webp|woff2)$/.test(relative))) {
      if (!info.size || info.size > 1024 * 1024) throw new Error(`Asset size exceeds bound: ${relative}`)
      files.push({ relative, body: await readFile(path) })
    } else throw new Error(`Unexpected production output: ${relative}`)
  }
}
await visit(root)
if (!files.some(file => file.relative === 'index.html') || files.length > 128 || files.reduce((n, f) => n + f.body.length, 0) > 8 * 1024 * 1024) {
  throw new Error('Missing index or oversized production bundle')
}
const mime = { html: 'text/html; charset=utf-8', js: 'text/javascript; charset=utf-8', css: 'text/css; charset=utf-8', svg: 'image/svg+xml', png: 'image/png', webp: 'image/webp', woff2: 'font/woff2' }
const source = ['// Generated by scripts/webui/embed-assets.mjs; do not edit.', '#include "web/static_assets.h"', 'namespace droidvm::web { namespace {']
function array(name, body) {
  source.push(`const unsigned char ${name}[] = {`)
  for (let offset = 0; offset < body.length; offset += 24) source.push([...body.subarray(offset, offset + 24)].join(',') + ',')
  source.push('};')
}
let compressedBytes = 0
files.forEach((file, index) => {
  file.gzip = gzipSync(file.body, { level: 9, mtime: 0 })
  if (file.gzip.length >= file.body.length) file.gzip = undefined
  file.etag = '"' + createHash('sha256').update(file.body).digest('hex') + '"'
  array(`asset_${index}`, file.body)
  if (file.gzip) array(`gzip_${index}`, file.gzip)
  compressedBytes += file.gzip?.length ?? file.body.length
})
source.push('const StaticAsset assets[] = {')
files.forEach((file, index) => source.push(`{${JSON.stringify('/' + file.relative)}, ${JSON.stringify(mime[file.relative.split('.').pop()])}, ${JSON.stringify(file.etag)}, {reinterpret_cast<const char*>(asset_${index}), sizeof(asset_${index})}, ${file.gzip ? `{reinterpret_cast<const char*>(gzip_${index}), sizeof(gzip_${index})}` : '{}'}},`))
source.push('};', '}', 'std::span<const StaticAsset> embedded_assets() { return assets; }', '}', '')
const output = resolve(values.output)
await mkdir(dirname(output), { recursive: true })
const content = source.join('\n')
if (await readFile(output, 'utf8').catch(() => null) !== content) {
  await writeFile(output + '.tmp', content)
  await rename(output + '.tmp', output)
}
console.log(`Embedded ${files.length} production assets: ${files.reduce((n, f) => n + f.body.length, 0)} bytes, ${compressedBytes} bytes with gzip`)
