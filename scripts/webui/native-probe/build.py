"""Build the isolated HTTP/WS probe without TLS or a cryptography dependency."""
import argparse
import os
import re
from pathlib import Path
import subprocess


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--target", choices=["windows", "arm64-v8a", "x86_64"], required=True)
    parser.add_argument("--component", choices=["transport", "core", "server"], default="transport")
    parser.add_argument("--ndk", type=Path)
    parser.add_argument("--assets", type=Path, help="Production assets generated by embed-assets.mjs")
    parser.add_argument("--clean", action="store_true", help="Rebuild generated targets from scratch")
    parser.add_argument("--output", type=Path, default=Path(__file__).resolve().parents[3] / "build/webui-native")
    args = parser.parse_args()
    root = args.output.resolve()
    root.mkdir(parents=True, exist_ok=True)
    common = ["-G", "Ninja", "-DCMAKE_BUILD_TYPE=Release"]
    common += [f"-DDROIDVM_WEB_ASSETS_CPP={args.assets.resolve().as_posix() if args.assets else ''}"]
    if args.target == "windows":
        # Run from an x64 VS developer shell; no system environment is changed.
        # Some VS installations only contain Chinese diagnostics. Capture the
        # actual prefix; Android SDK CMake 3.22 can misdecode auto-detection.
        os.environ["VSLANG"] = "1033"
        source = root / "msvc-includes.c"
        source.write_text("#include <stdio.h>\nint main(void) { return 0; }\n", encoding="utf-8")
        detected = subprocess.run(["cl", "/nologo", "/showIncludes", "/c", str(source),
            f"/Fo{root / 'msvc-includes.obj'}"], capture_output=True, check=True)
        diagnostics = (detected.stdout + detected.stderr).decode("utf-8")
        match = re.search(r"^(.*?)[A-Za-z]:[\\/].*stdio\.h\s*$", diagnostics, re.MULTILINE)
        if not match:
            raise RuntimeError("Could not detect MSVC include prefix")
        hook = root / "msvc-includes.cmake"
        hook.write_text('if(MSVC)\n  set(CMAKE_CL_SHOWINCLUDES_PREFIX "' + match[1] + '")\nendif()\n', encoding="utf-8")
        common += [f"-DCMAKE_PROJECT_INCLUDE={hook.as_posix()}"]
        common += ["-DCMAKE_C_COMPILER=cl", "-DCMAKE_C_FLAGS=/utf-8"]
        if args.component != "transport":
            common += ["-DCMAKE_CXX_COMPILER=cl", "-DCMAKE_CXX_FLAGS=/utf-8 /EHsc"]
    else:
        if not args.ndk:
            parser.error("--ndk is required for Android")
        common += [f"-DCMAKE_TOOLCHAIN_FILE={args.ndk.resolve().as_posix()}/build/cmake/android.toolchain.cmake",
                   f"-DANDROID_ABI={args.target}", "-DANDROID_PLATFORM=android-33"]

    def run(label, command):
        log = root / f"{args.target}-http-{args.component}-{label}.log"
        with log.open("w", encoding="utf-8") as output:
            result = subprocess.run(command, stdout=output, stderr=subprocess.STDOUT, check=False)
        if result.returncode:
            raise RuntimeError(f"{label} failed ({result.returncode}); see {log}")
        print(f"{args.target}: {label} passed", flush=True)

    build_name = "windows-msvc" if args.target == "windows" else args.target
    suffix = {"core": "web-core", "server": "web-server", "transport": "http-probe"}[args.component]
    probe = root / f"{build_name}-{suffix}"
    source = Path(__file__).resolve().parents[3] / "daemon/web" if args.component != "transport" else Path(__file__).resolve().parent
    if args.component != "transport":
        common += [f"-DDROIDVM_JSONCPP_DIR={(Path(__file__).resolve().parents[3] / 'app/src/main/cpp/jsoncpp').as_posix()}"]
    if args.component == "server":
        common += ["-DDROIDVM_WEB_HTTP_TRANSPORT=ON", f"-DDROIDVM_WEB_LWS_DIR={(root / 'deps/libwebsockets').as_posix()}"]
    clean = ["--clean-first"] if args.clean else []
    run("probe-configure", ["cmake", "-S", str(source), "-B", str(probe), *common,
        f"-DPROBE_DEPS={(root / 'deps').as_posix()}"])
    run("probe-build", ["cmake", "--build", str(probe), "--parallel", "4", *clean])


if __name__ == "__main__":
    main()
